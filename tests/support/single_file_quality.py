"""Synthetic B04 handoffs for the current single-episode contract.

These fixtures exercise delivery and storage. Their verdicts and statistical
digest are deliberately prepared test evidence, not outputs of a fitted model.
The independent container fixtures are generated by the actual B01–B03 logic.
"""
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
from uuid import UUID

from pretrain_cleaning_common.artifact import pack_artifact
from pretrain_cleaning_common.handoff import REVISION, SOURCE_REVISION, profile_digest
from pretrain_cleaning_common.reporting import quality_counts
from pretrain_cleaning_common.single_file import validate_cohort, write_cohort


def _digest(value):
    return hashlib.sha256(json.dumps(
        value, ensure_ascii=False, allow_nan=False, sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class DeliveryFixture:
    quality_files: tuple[Path, ...]
    raw_files: dict[str, Path]


def delivery_fixture(folder, statuses=("kept", "rejected"), *, diagnostic=False):
    """Create one original and one quality ZIP per episode, sharing a full cohort."""
    folder = Path(folder).resolve()
    if not statuses:
        raise ValueError("delivery fixture requires at least one episode")
    raw = folder / "raw"
    raw.mkdir()
    members, records, mapping = [], [], {}
    # Sorting here keeps IDs in the same order as the cohort's logical keys.
    for index, (key, original_index, status) in enumerate(sorted(
        (f"capture/e{i}/episode.mcap", i, status) for i, status in enumerate(statuses)
    )):
        if status not in {"kept", "rejected"}:
            raise ValueError("unsupported delivery fixture verdict")
        path = raw / f"{index}.mcap"
        path.write_bytes(f"original-{index}".encode())
        source = {
            "attempt_id": str(UUID(int=original_index + 1)), "input_name": "raw_files", "input_index": 0,
            "logical_key": key, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }
        member = {"episode_index": index, "source_ref": source}
        members.append(member)
        records.append({
            **member, "source": key, "status": status, "reject_file": status == "rejected",
            "diagnostic_errors": {"stage": "broken"} if diagnostic else {},
        })
        mapping[key] = path
    cohort = {
        "format": "mcap_cohort_v1", "source": "jindian_marvin",
        "profile_digest": profile_digest("jindian_marvin"),
        "source_revision": SOURCE_REVISION, "engine_revision": REVISION,
        "members": [{**member, "normalized_digest": _digest({"fixture_normalized": member})}
                    for member in members],
    }
    cohort["cohort_id"] = _digest(cohort)
    validate_cohort(cohort)
    statistics_digest = _digest({"fixture_statistics": "delivery-v6", "cohort_id": cohort["cohort_id"]})
    archives = []
    for member, record in zip(members, records, strict=True):
        index = member["episode_index"]
        payload = folder / f"quality-{index}"
        payload.mkdir()
        (payload / "selection.json").write_text(json.dumps({
            "source": "jindian_marvin", "members": [member],
        }))
        (payload / "decisions.jsonl").write_text(json.dumps(record) + "\n")
        (payload / "quality_summary.json").write_text(json.dumps({
            "statistics_status": "ready", "statistics_context_digest": statistics_digest,
            **quality_counts([record]),
        }))
        write_cohort(payload, cohort)
        archive = folder / f"quality-{index}.zip"
        pack_artifact(archive, "quality_batch", payload)
        archives.append(archive)
    return DeliveryFixture(tuple(archives), mapping)
